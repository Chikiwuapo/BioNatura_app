package com.goku1.bionatura;

public class HistorialItem {

    String fecha, entrada, salida, lugar, horas, estado;

    public HistorialItem(String fecha, String entrada, String salida, String lugar, String horas, String estado) {
        this.fecha = fecha;
        this.entrada = entrada;
        this.salida = salida;
        this.lugar = lugar;
        this.horas = horas;
        this.estado = estado;
    }
}
